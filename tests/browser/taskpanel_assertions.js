"use strict";
window.addEventListener("DOMContentLoaded", async () => {
  const $ = id => document.getElementById(id);
  const passed = [];
  function check(value, label) { if (!value) throw new Error(label); passed.push(label); document.body.dataset.tests = passed.join("；"); }
  async function until(test, label) { for (let i = 0; i < 200; i++) { if (test()) return; await fetch("/api/jobs", {cache: "no-store"}); if (window.IrisConsole) await window.IrisConsole.refresh(); await new Promise(resolve => setTimeout(resolve, 20)); } throw new Error("等待超时：" + label); }
  try {
    await until(() => $("catalog-grid").querySelectorAll("article").length > 20, "真实目录");
    check(document.querySelector('meta[name="iris-token"]').content !== "__IRIS_TOKEN__", "令牌替换");
    check($("status-text").textContent.includes("已连接"), "真实状态API");
    await until(() => $("overview-grid").children.length === 8, "总览分区");
    check(!$("view-overview").hidden, "默认首页总览");
    document.querySelector('[data-view="wizards"]').click();
    check($("wizard-tabs").children.length === 5, "五类向导入口");
    document.querySelector('[data-wizard="feishu"]').click();
    check($("feishu-confirm-button").disabled, "预览前禁止导入");
    $("wizard-feishu-url").value = "https://example.feishu.cn/docx/test";
    $("wizard-feishu-url").dispatchEvent(new Event("input", {bubbles: true}));
    document.querySelector('[data-action="feishu-preview"]').click();
    await until(() => !$("feishu-confirm-button").disabled, "预览成功开放下一步");
    check(document.querySelector(".wizard-steps").textContent.includes("成功"), "向导跟踪真实任务终态");
    $("wizard-feishu-url").value = "https://example.feishu.cn/docx/changed";
    $("wizard-feishu-url").dispatchEvent(new Event("input", {bubbles: true}));
    check($("feishu-confirm-button").disabled, "URL变化清空预览关联");
    document.querySelector('[data-wizard="wiki"]').click();
    check(document.querySelector('[data-action="wiki-write"]').disabled, "Wiki预览前禁止写入");
    check(document.querySelector('[data-action="wiki-lint"]').disabled, "Wiki写入前禁止下一步");
    await until(() => !document.querySelector('[data-action="wiki-discover"]').disabled, "Wiki列表就绪");
    document.querySelector('[data-action="wiki-discover"]').click();
    await until(() => document.querySelector('.candidate-row input') && !document.querySelector('.candidate-row input').disabled, "Wiki发现候选");
    document.querySelector('.candidate-row input').click();
    document.querySelector('[data-action="wiki-select"]').click();
    await until(() => !document.querySelector('[data-action="wiki-preview"]').disabled, "Wiki保存审核选择");
    document.querySelector('[data-action="wiki-preview"]').click();
    await until(() => !document.querySelector('[data-action="wiki-write"]').disabled, "Wiki草稿预览成功");
    window.confirm = () => true;
    document.querySelector('[data-action="wiki-write"]').click();
    await until(() => !document.querySelector('[data-action="wiki-lint"]').disabled, "Wiki写入成功");
    document.querySelector('[data-action="wiki-lint"]').click();
    await until(() => [...document.querySelectorAll('.wizard-step')].some(row => row.textContent.includes('wiki-lint') && row.textContent.includes('成功')), "Wiki质量检查完成");
    check(true, "Wiki发现选择预览写入检查完整流程");
    document.dispatchEvent(new KeyboardEvent("keydown", {key: "k", ctrlKey: true, bubbles: true}));
    check($("search-dialog").open, "Ctrl K打开搜索");
    $("quick-search").value = "deep-eval";
    $("quick-search").dispatchEvent(new Event("input", {bubbles: true}));
    $("quick-search").dispatchEvent(new KeyboardEvent("keydown", {key: "Enter", bubbles: true}));
    check($("command-dialog").open && $("command-title").textContent === "deep-eval", "搜索Enter选择命令");
    check($("param-sample_rate").type === "number" && $("param-sample_rate").step === "any", "float步长");
    $("param-sample_rate").value = "0.25";
    $("param-sample_rate").dispatchEvent(new Event("input", {bubbles: true}));
    check($("cli-preview").textContent.includes("0.25"), "等价CLI预览");
    $("command-dialog").close();
    window.IrisConsole.openCommand("decisions");
    $("param-action").value = "show";
    $("param-action").dispatchEvent(new Event("change", {bubbles: true}));
    check($("param-subject").required && !$("param-days"), "子操作目标与参数子集");
    $("command-dialog").close();
    window.IrisConsole.openCommand("watch");
    check($("command-submit").disabled && !$("command-warning").hidden, "blocked禁止执行");
    $("command-dialog").close();
    window.IrisConsole.openCommand("working-clear");
    window.confirm = () => false;
    $("command-form").requestSubmit();
    check($("command-dialog").open && !$("command-submit").disabled, "取消确认不提交");
    $("command-dialog").close();
    window.IrisConsole.openCommand("status");
    $("command-form").requestSubmit();
    await until(() => $("job-dialog").open, "真实POST启动");
    await until(() => $("stdout-log").textContent.includes("控制台日志"), "stdout读取");
    await until(() => $("stderr-log").textContent.includes("diagnostic"), "stderr读取");
    check($("stdout-log").textContent.includes("<img src=x"), "日志保留危险文本原样");
    check(!$("stdout-log").querySelector("img") && !window.__xss, "日志不执行HTML");
    check($("job-cli").textContent.includes("fake_cli.py"), "真实runner argv");
    const text = $("stdout-log").textContent;
    await window.IrisConsole.refresh();
    check($("stdout-log").textContent === text, "字节offset不重复追加");
    $("job-dialog").close();
    document.querySelector('[data-view="catalog"]').click();
    check(!$("view-catalog").hidden, "目录导航");
    check(document.documentElement.scrollWidth <= window.innerWidth + 1, "页面无横向溢出");
    document.body.dataset.testResult = "PASS";
  } catch (error) { document.body.dataset.testResult = "FAIL: " + error.message; }
});
